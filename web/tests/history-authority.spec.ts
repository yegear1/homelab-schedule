import { expect, test } from './fixtures';
const run = { id: 'run-one', job_id: 'job-one', ran_at: '2024-02-01T12:00:00Z', trigger: 'manual', status: 'error', status_code: 500, duration_ms: 42, error_message: 'gateway unavailable' };
const job = { id: 'job-one', title: 'Real job', content: 'Stored content', to: '123', target_number: '123', kind: 'once', run_at: '2030-01-01T12:00:00Z', cron_expr: null, enabled: true, source: 'sqlite', status: 'scheduled', next_run_at: '2030-01-01T12:00:00Z', last_run_at: null, last_status: null, last_error: null, retry_count: 0, created_by: '', template_id: null, tags: [], variables: {} };
test.beforeEach(async ({ page }) => { await page.addInitScript(() => localStorage.setItem('SCHEDULE_API_KEY', 'synthetic-key')); });
test('history failure is distinct and failed export creates no file', async ({ page }) => {
  let failed = true;
  await page.route('**/jobs/runs?*', (route) => failed ? route.fulfill({ status: 503, json: { detail: 'history offline' } }) : route.fulfill({ json: { runs: [run] } }));
  await page.route('**/jobs/runs/export.csv?*', (route) => route.fulfill({ status: 503, json: { detail: 'export offline' } }));
  await page.goto('/history');
  await expect(page.getByRole('alert')).toContainText('history offline');
  await expect(page.getByText('Nenhuma tentativa encontrada.')).toHaveCount(0);
  failed = false;
  await page.getByRole('button', { name: 'Tentar novamente' }).click();
  await expect(page.getByText('job-one')).toBeVisible();
  let downloads = 0;
  page.on('download', () => { downloads++; });
  await page.getByRole('button', { name: 'Exportar CSV' }).click();
  await expect(page.getByText(/Falha ao exportar CSV/)).toBeVisible();
  expect(downloads).toBe(0);
  await page.getByRole('button', { name: 'Detalhes' }).click();
  await expect(page.getByRole('dialog')).toContainText('gateway unavailable');
  await expect(page.getByRole('dialog')).not.toContainText('Payload Snapshot');
});
test('inspector reports runs errors, empty projection, and missing detail', async ({ page }) => {
  await page.route('**/jobs/runs?*', (route) => route.fulfill({ json: { runs: [run] } }));
  await page.route('**/jobs/job-one/runs?*', (route) => route.fulfill({ status: 503, json: { detail: 'runs offline' } }));
  await page.route('**/jobs/job-one/upcoming?*', (route) => route.fulfill({ json: { runs: [] } }));
  let missing = false;
  await page.route('**/jobs/job-one', (route) => missing ? route.fulfill({ status: 404, json: { detail: 'missing' } }) : route.fulfill({ json: job }));
  await page.goto('/history');
  await page.getByRole('button', { name: 'job-one' }).click();
  await expect(page.getByText('Stored content')).toBeVisible();
  await page.getByRole('button', { name: 'Audit Runs' }).click();
  await expect(page.getByRole('alert')).toContainText('runs offline');
  await expect(page.locator('#runs-empty')).toHaveCount(0);
  await page.getByRole('button', { name: 'Upcoming' }).click();
  await expect(page.locator('#upcoming-empty')).toBeVisible();
  await page.keyboard.press('Escape');
  missing = true;
  await page.getByRole('button', { name: 'job-one' }).click();
  await expect(page.getByRole('alert')).toContainText('Agendamento não encontrado');
});
test('late detail response cannot replace a newer selection', async ({ page }) => {
  const secondRun = { ...run, id: 'run-two', job_id: 'job-two' };
  await page.route('**/jobs/runs?*', (route) => route.fulfill({ json: { runs: [run, secondRun] } }));
  let release: (() => void) | undefined;
  const gate = new Promise<void>((resolve) => { release = resolve; });
  await page.route('**/jobs/job-one', async (route) => { await gate; await route.fulfill({ json: job }).catch(() => {}); });
  await page.route('**/jobs/job-two', (route) => route.fulfill({ json: { ...job, id: 'job-two', title: 'Second job', content: 'Second content' } }));
  await page.route('**/jobs/*/runs?*', (route) => route.fulfill({ json: { runs: [] } }));
  await page.route('**/jobs/*/upcoming?*', (route) => route.fulfill({ json: { runs: [] } }));
  await page.goto('/history');
  await page.getByRole('button', { name: 'job-one' }).click();
  await expect(page.getByText('Carregando detalhes…')).toBeVisible();
  await page.getByRole('button', { name: 'Fechar' }).click();
  await page.getByRole('button', { name: 'job-two' }).click();
  await expect(page.getByText('Second content')).toBeVisible();
  release?.();
  await expect(page.getByText('Second content')).toBeVisible();
  await expect(page.getByText('Stored content')).toHaveCount(0);
});
test('history job outside agenda can run through guarded mutation', async ({ page }) => {
  await page.route('**/jobs/runs?*', (route) => route.fulfill({ json: { runs: [run] } }));
  await page.route('**/jobs/job-one', (route) => route.fulfill({ json: job }));
  await page.route('**/jobs/job-one/runs?*', (route) => route.fulfill({ json: { runs: [] } }));
  await page.route('**/jobs/job-one/upcoming?*', (route) => route.fulfill({ json: { runs: [] } }));
  let writes = 0;
  await page.route('**/jobs/job-one/run', (route) => { writes++; return route.fulfill({ status: 202, json: { status: 'queued', job_id: 'job-one' } }); });
  await page.goto('/history');
  await page.getByRole('button', { name: 'job-one' }).click();
  await page.getByRole('button', { name: 'Run Now' }).click();
  await expect(page.getByText('Queued Real job')).toBeVisible();
  expect(writes).toBe(1);
});
